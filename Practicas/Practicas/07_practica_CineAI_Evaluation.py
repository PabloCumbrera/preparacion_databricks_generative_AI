def build_evaluation_record(row: dict) -> dict:
    """Convert a CineAI evaluation row into an MLflow record.

    Args:
        row: Source record containing the question, expected
            response, expected tool calls, and metadata.

    Returns:
        An MLflow-compatible evaluation record.

    Raises:
        ValueError: If required fields are missing or tool
            call expectations contain invalid JSON.
    """
    question = row.get("question")
    expected_answer = row.get("expected_answer")

    if not question or not expected_answer:
        raise ValueError("Missing question or expected answer")

    raw_tool_calls = row.get("expected_tool_calls_json") or "[]"

    tool_calls = json.loads(raw_tool_calls)

    # Remove unspecified arguments for name-only matching.
    tool_calls = [
        {
            key: value
            for key, value in tool_call.items()
            if key != "arguments" or value
        }
        for tool_call in tool_calls
    ]

    return {
        "inputs": {
            "question": question
        },
        "expectations": {
            "expected_response": expected_answer,
            "expected_tool_calls": tool_calls
        },
        "tags": {
            "eval_id": str(row["eval_id"]),
            "intent": str(row["intent"]),
            "difficulty": str(row["difficulty"]),
            "expected_source": str(row["expected_source"]),
            "tool_match_policy": str(row["tool_match_policy"])
        }
    }


